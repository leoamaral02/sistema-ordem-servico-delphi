/* Triggers only will work for SQL triggers */
CREATE TRIGGER TRG_ITEM_RECALC_TOTAL FOR ITEM_ORDEM 
ACTIVE AFTER INSERT OR UPDATE OR DELETE POSITION 0 
AS

DECLARE VARIABLE V_ORDEM_ID INTEGER;
BEGIN
  IF (INSERTING OR UPDATING) THEN
    V_ORDEM_ID = NEW.ORDEM_ID;
  ELSE
    V_ORDEM_ID = OLD.ORDEM_ID;

  UPDATE ORDEM_SERVICO
  SET VALOR_TOTAL = COALESCE(
        (SELECT SUM(QUANTIDADE * VALOR_UNITARIO)
         FROM ITEM_ORDEM
         WHERE ORDEM_ID = :V_ORDEM_ID), 0)
  WHERE ID = :V_ORDEM_ID;

  IF (UPDATING AND (OLD.ORDEM_ID <> NEW.ORDEM_ID)) THEN
    UPDATE ORDEM_SERVICO
    SET VALOR_TOTAL = COALESCE(
          (SELECT SUM(QUANTIDADE * VALOR_UNITARIO)
           FROM ITEM_ORDEM
           WHERE ORDEM_ID = OLD.ORDEM_ID), 0)
    WHERE ID = OLD.ORDEM_ID;



end ^


SET TERM ; ^
