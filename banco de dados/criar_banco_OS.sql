/* Table: CLIENTE, Owner: SYSDBA */
CREATE TABLE CLIENTE (ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        NOME VARCHAR(120) NOT NULL,
        DOCUMENTO VARCHAR(20),
        EMAIL VARCHAR(120),
        TELEFONE VARCHAR(30),
        DATACADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
PRIMARY KEY (ID));

/* Table: ITEM_ORDEM, Owner: SYSDBA */
CREATE TABLE ITEM_ORDEM (ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        ORDEM_ID INTEGER NOT NULL,
        DESCRICAO VARCHAR(200) NOT NULL,
        QUANTIDADE NUMERIC(12, 2) NOT NULL,
        VALOR_UNITARIO NUMERIC(15, 2) NOT NULL,
PRIMARY KEY (ID));

/* Table: ORDEM_SERVICO, Owner: SYSDBA */
CREATE TABLE ORDEM_SERVICO (ID INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
        CLIENTE_ID INTEGER NOT NULL,
        DATA_ABERTURA DATE NOT NULL,
        DATA_PREVISTA DATE,
        DATA_FECHAMENTO DATE,
        STATUS VARCHAR(15) NOT NULL,
        DESCRICAO_PROBLEMA VARCHAR(500),
        VALOR_TOTAL NUMERIC(15, 2) DEFAULT 0,
PRIMARY KEY (ID));

/*  Index definitions for all user tables */
CREATE INDEX IDX_OS_CLIENTE ON ORDEM_SERVICO (CLIENTE_ID);
CREATE INDEX IDX_OS_DATA_ABERTURA ON ORDEM_SERVICO (DATA_ABERTURA);
CREATE INDEX IDX_OS_STATUS ON ORDEM_SERVICO (STATUS);

ALTER TABLE ITEM_ORDEM ADD CONSTRAINT FK_ITEM_ORDEM FOREIGN KEY (ORDEM_ID) REFERENCES ORDEM_SERVICO (ID);

ALTER TABLE ORDEM_SERVICO ADD CONSTRAINT FK_OS_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE (ID);

/* View: VW_OS_RESUMO, Owner: SYSDBA */
CREATE VIEW VW_OS_RESUMO (ID, CLIENTE_ID, CLIENTE_NOME, DATA_ABERTURA, DATA_PREVISTA, DATA_FECHAMENTO, STATUS, VALOR_TOTAL, EM_ATRASO) AS
SELECT
  O.ID, O.CLIENTE_ID, C.NOME AS CLIENTE_NOME,
  O.DATA_ABERTURA, O.DATA_PREVISTA, O.DATA_FECHAMENTO,
  O.STATUS, O.VALOR_TOTAL,
  CASE
    WHEN (O.STATUS NOT IN ('Concluída','Cancelada'))
     AND (O.DATA_PREVISTA IS NOT NULL)
     AND (CURRENT_DATE > O.DATA_PREVISTA)
    THEN 1 ELSE 0 END AS EM_ATRASO
FROM ORDEM_SERVICO O
JOIN CLIENTE C ON C.ID = O.CLIENTE_ID;

/* Table constraints */

